function applyLanguage(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const dict = I18N[lang];
    if (dict && dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });
  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) langBtn.setAttribute("data-active", lang);
  localStorage.setItem("marcus-portfolio-lang", lang);
  if (window.renderPlayers) window.renderPlayers(lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("marcus-portfolio-lang");
  const initialLang = saved === "es" || saved === "en" ? saved : "en";
  applyLanguage(initialLang);

  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) {
    langBtn.addEventListener("click", () => {
      const current = langBtn.getAttribute("data-active") === "en" ? "en" : "es";
      applyLanguage(current === "es" ? "en" : "es");
    });
  }
});
